#!/bin/sh
# Regenerates the core-api DTOs from a published contract version (never from services/contracts by path).
# Usage: NODE_AUTH_TOKEN=... scripts/generate-contracts.sh <contract version>   (run from services/core-backend)
# Output: src/Esi.Core.Api/Contracts/CoreApi.g.cs and CONTRACT_VERSION. Generated code is never edited by hand.
set -eu

VERSION="${1:?usage: scripts/generate-contracts.sh <contract version>}"
: "${NODE_AUTH_TOKEN:?NODE_AUTH_TOKEN with read:packages is required (see docs/process/github-setup.md)}"
OUT_DIR="src/Esi.Core.Api/Contracts"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

# 1. Fetch the bundled spec from the package registry.
docker run --rm -e NODE_AUTH_TOKEN -e VERSION="$VERSION" -v "$WORK:/work" -w /work node:22.23.3-alpine3.24 sh -c '
  printf "%s\n" "@dtnam0899:registry=https://npm.pkg.github.com" "//npm.pkg.github.com/:_authToken=\${NODE_AUTH_TOKEN}" > .npmrc
  npm pack "@dtnam0899/esi-contracts@$VERSION" --silent >/dev/null
  tar -xzf ./*.tgz package/bundled/core-api.yaml
  rm .npmrc'

# 2. Generate DTO types only (no client, no controllers) with the pinned NSwag tool.
docker run --rm -v "$PWD:/src" -v "$WORK:/work" -w /src -e DOTNET_CLI_TELEMETRY_OPTOUT=1 -e DOTNET_NOLOGO=1 \
  mcr.microsoft.com/dotnet/sdk:10.0.402-noble sh -c '
  dotnet tool restore >/dev/null
  DOTNET_ROLL_FORWARD=Major dotnet tool run nswag openapi2csclient /input:/work/package/bundled/core-api.yaml \
    /output:/work/CoreApi.g.cs /namespace:Esi.Core.Api.Contracts \
    /generateClientClasses:false /generateClientInterfaces:false /generateExceptionClasses:false \
    /generateDtoTypes:true /jsonLibrary:SystemTextJson /classStyle:Poco \
    /generateNullableReferenceTypes:true /generateOptionalPropertiesAsNullable:true \
    /generateDataAnnotations:false /generateDefaultValues:true /arrayType:System.Collections.Generic.List \
    /arrayInstanceType:System.Collections.Generic.List /dateTimeType:System.DateTimeOffset >/dev/null'

{
  echo "// <auto-generated>"
  echo "// Generated from @dtnam0899/esi-contracts@$VERSION (bundled/core-api.yaml) by scripts/generate-contracts.sh with NSwag."
  echo "// Do not edit by hand; regenerate after bumping the contract version."
  echo "// </auto-generated>"
  # System.Text.Json ignores EnumMember; map the contract's enum strings with JsonStringEnumMemberName (.NET 9+).
  sed -E 's/\[System\.Runtime\.Serialization\.EnumMember\(Value = @"([^"]*)"\)\]/[System.Text.Json.Serialization.JsonStringEnumMemberName("\1")]/' "$WORK/CoreApi.g.cs"
} > "$OUT_DIR/CoreApi.g.cs"
echo "$VERSION" > "$OUT_DIR/CONTRACT_VERSION"
echo "Generated $OUT_DIR/CoreApi.g.cs from contracts $VERSION"
