#!/bin/sh
# Refreshes everything core-backend takes from published packages (never from other projects by path), at the
# versions pinned in published-packages.json:
#   @dtnam0899/esi-contracts -> src/Esi.Core.Api/Contracts/CoreApi.g.cs (core-api DTOs)
#                               src/Esi.Core.Infrastructure/Agents/AgentsApi.g.cs (agents-api client)
#   @dtnam0899/dsl-schema    -> src/Esi.Core.Infrastructure/Dsl/Schema/ (A2UI v0.9.1 catalog and common types)
#                               tests/Esi.Core.UnitTests/Fixtures/dsl-schema/ (shared valid/invalid fixtures)
# Each target records its source in a PUBLISHED.json / header. Generated and vendored files are never edited.
# Usage (from services/core-backend): NODE_AUTH_TOKEN=$(gh auth token) scripts/sync-published.sh
set -eu

: "${NODE_AUTH_TOKEN:?NODE_AUTH_TOKEN with read:packages is required (see docs/process/github-setup.md)}"
version_of() { sed -n "s/.*\"$1\": *\"\([^\"]*\)\".*/\1/p" published-packages.json; }
CONTRACTS="$(version_of '@dtnam0899\/esi-contracts')"
DSL_SCHEMA="$(version_of '@dtnam0899\/dsl-schema')"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

# 1. Download both packages.
docker run --rm -e NODE_AUTH_TOKEN -e CONTRACTS="$CONTRACTS" -e DSL_SCHEMA="$DSL_SCHEMA" -v "$WORK:/work" -w /work \
  node:22.23.3-alpine3.24 sh -c '
  printf "%s\n" "@dtnam0899:registry=https://npm.pkg.github.com" "//npm.pkg.github.com/:_authToken=\${NODE_AUTH_TOKEN}" > .npmrc
  mkdir contracts dsl-schema
  npm pack "@dtnam0899/esi-contracts@$CONTRACTS" --silent --pack-destination contracts >/dev/null
  npm pack "@dtnam0899/dsl-schema@$DSL_SCHEMA" --silent --pack-destination dsl-schema >/dev/null
  tar -xzf contracts/*.tgz -C contracts && tar -xzf dsl-schema/*.tgz -C dsl-schema
  rm .npmrc'

# 2. Generate the core-api DTOs and the agents-api client with the pinned NSwag tool.
docker run --rm -v "$PWD:/src" -v "$WORK:/work" -w /src -e DOTNET_CLI_TELEMETRY_OPTOUT=1 -e DOTNET_NOLOGO=1 \
  mcr.microsoft.com/dotnet/sdk:10.0.402-noble sh -c '
  dotnet tool restore >/dev/null
  export DOTNET_ROLL_FORWARD=Major
  common="/jsonLibrary:SystemTextJson /classStyle:Poco /generateNullableReferenceTypes:true /generateOptionalPropertiesAsNullable:true /generateDataAnnotations:false /generateDefaultValues:true /arrayType:System.Collections.Generic.List /arrayInstanceType:System.Collections.Generic.List /dateTimeType:System.DateTimeOffset"
  dotnet tool run nswag openapi2csclient /input:/work/contracts/package/bundled/core-api.yaml /output:/work/CoreApi.g.cs \
    /namespace:Esi.Core.Api.Contracts /generateClientClasses:false /generateClientInterfaces:false \
    /generateExceptionClasses:false /generateDtoTypes:true $common >/dev/null
  dotnet tool run nswag openapi2csclient /input:/work/contracts/package/bundled/agents-api.yaml /output:/work/AgentsApi.g.cs \
    /namespace:Esi.Core.Infrastructure.Agents.Contracts /className:AgentsApiClient /generateClientClasses:true \
    /generateClientInterfaces:true /injectHttpClient:true /useBaseUrl:false /exceptionClass:AgentsApiException \
    /generateDtoTypes:true $common >/dev/null'

header() {
  echo "// <auto-generated>"
  echo "// Generated from @dtnam0899/esi-contracts@$CONTRACTS ($1) by scripts/sync-published.sh with NSwag."
  echo "// Do not edit by hand; bump published-packages.json and rerun the script."
  echo "// </auto-generated>"
}
# System.Text.Json ignores EnumMember; map the contract's enum strings with JsonStringEnumMemberName (.NET 9+).
enum_names() {
  sed -E 's/\[System\.Runtime\.Serialization\.EnumMember\(Value = @"([^"]*)"\)\]/[System.Text.Json.Serialization.JsonStringEnumMemberName("\1")]/' "$1"
}
{ header bundled/core-api.yaml; enum_names "$WORK/CoreApi.g.cs"; } > src/Esi.Core.Api/Contracts/CoreApi.g.cs
mkdir -p src/Esi.Core.Infrastructure/Agents
{ header bundled/agents-api.yaml; enum_names "$WORK/AgentsApi.g.cs"; } > src/Esi.Core.Infrastructure/Agents/AgentsApi.g.cs
echo "$CONTRACTS" > src/Esi.Core.Api/Contracts/CONTRACT_VERSION

# 3. Vendor the DSL schema files and the shared fixtures.
published() { printf '{\n  "package": "@dtnam0899/dsl-schema",\n  "version": "%s",\n  "source": "%s"\n}\n' "$DSL_SCHEMA" "$1"; }
SCHEMA_DIR=src/Esi.Core.Infrastructure/Dsl/Schema
FIXTURE_DIR=tests/Esi.Core.UnitTests/Fixtures/dsl-schema
rm -rf "$SCHEMA_DIR" "$FIXTURE_DIR" && mkdir -p "$SCHEMA_DIR" "$FIXTURE_DIR"
cp "$WORK/dsl-schema/package/src/a2ui/v0_9_1/catalog.json" "$WORK/dsl-schema/package/src/a2ui/v0_9_1/common_types.json" \
   "$WORK/dsl-schema/package/src/a2ui/v0_9_1/PROVENANCE.md" "$SCHEMA_DIR/"
published "src/a2ui/v0_9_1" > "$SCHEMA_DIR/PUBLISHED.json"
cp -R "$WORK/dsl-schema/package/src/fixtures/valid" "$WORK/dsl-schema/package/src/fixtures/invalid" "$FIXTURE_DIR/"
published "src/fixtures" > "$FIXTURE_DIR/PUBLISHED.json"
echo "Synced esi-contracts $CONTRACTS and dsl-schema $DSL_SCHEMA"
