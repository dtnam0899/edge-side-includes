// Regenerates the core-api client in src/app/core/api/generated from the pinned contract package.
// The pin is `esi.coreApiContract` in package.json. The package is fetched only here (needs NODE_AUTH_TOKEN,
// see docs/process/github-setup.md), so installing and building the portal never needs a registry token.
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

import { createClient } from '@hey-api/openapi-ts';

import config from '../openapi-ts.config.mjs';

const OUTPUT = 'src/app/core/api/generated';

const version = JSON.parse(readFileSync('package.json', 'utf8')).esi?.coreApiContract;
if (!/^\d+\.\d+\.\d+$/.test(version ?? '')) {
  throw new Error('package.json: "esi.coreApiContract" must be an exact version');
}

const work = mkdtempSync(join(tmpdir(), 'esi-contracts-'));
try {
  const tarball = execFileSync(
    'npm',
    ['pack', '--silent', `@dtnam0899/esi-contracts@${version}`, '--pack-destination', work],
    {
      encoding: 'utf8',
    },
  ).trim();
  execFileSync('tar', ['-xzf', join(work, tarball), '-C', work]);
  await createClient({ ...(await config), input: join(work, 'package/bundled/core-api.yaml') });
  writeFileSync(
    join(OUTPUT, 'contract-version.gen.ts'),
    `// This file is auto-generated by scripts/generate-api.mjs\n\n/** Version of @dtnam0899/esi-contracts the client was generated from. */\nexport const CORE_API_CONTRACT_VERSION = '${version}';\n`,
  );
  console.log(`core-api client generated from @dtnam0899/esi-contracts ${version}`);
} finally {
  rmSync(work, { recursive: true, force: true });
}
